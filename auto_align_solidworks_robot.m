function auto_align_solidworks_robot()
% AUTO_ALIGN_SOLIDWORKS_ROBOT
% Safely validate a Simscape Multibody Link XML + STL export and import it
% into a NEW Simulink model. Does not modify the original XML/STL files.
%
% IMPORTANT:
% An XML export can contain many local joint/body transforms. Blindly
% subtracting an XYZ offset from every transform would corrupt the assembly.
% This script therefore validates the package and imports a separate model.
% The Base frame must be identified in the generated model before applying
% a single global Base-to-World transform. See the instructions printed below.

    clc;
    fprintf('=== SolidWorks XML/STL robot import checker ===\n');

    [xmlName, xmlFolder] = uigetfile( ...
        {'*.xml','Simscape Multibody Link XML (*.xml)'}, ...
        'Select the XML exported from SolidWorks');
    if isequal(xmlName,0)
        fprintf('Cancelled: no XML selected.\n');
        return;
    end
    xmlPath = fullfile(xmlFolder, xmlName);

    % Parse XML to catch malformed files.
    try
        doc = xmlread(xmlPath);
        root = doc.getDocumentElement();
        rootName = char(root.getNodeName());
    catch ME
        error('Cannot parse XML file: %s', ME.message);
    end

    % Find STL files below the XML folder.
    stlFiles = dir(fullfile(xmlFolder, '**', '*.stl'));
    if isempty(stlFiles)
        warning(['No STL files found below the XML folder. ', ...
                 'Check that all exported geometry files are present.']);
    else
        fprintf('Found %d STL file(s).\n', numel(stlFiles));
    end

    % Check for XML references to STL files and missing referenced files.
    xmlText = fileread(xmlPath);
    stlTokens = regexp(xmlText, '[^"''<> \t\r\n]+\.stl', 'match');
    stlTokens = unique(stlTokens, 'stable');
    missingRefs = {};
    for k = 1:numel(stlTokens)
        ref = strrep(stlTokens{k}, '/', filesep);
        % Try relative to XML folder, then by basename under the folder.
        candidate = fullfile(xmlFolder, ref);
        if ~isfile(candidate)
            [~, base, ext] = fileparts(ref);
            found = dir(fullfile(xmlFolder, '**', [base ext]));
            if isempty(found)
                missingRefs{end+1} = stlTokens{k}; %#ok<AGROW>
            end
        end
    end

    fprintf('\nXML: %s\n', xmlPath);
    fprintf('XML root element: %s\n', rootName);
    fprintf('STL references detected in XML: %d\n', numel(stlTokens));
    if ~isempty(missingRefs)
        fprintf(2, '\nPotentially missing STL reference(s):\n');
        for k = 1:numel(missingRefs)
            fprintf(2, '  - %s\n', missingRefs{k});
        end
        fprintf(2, ['\nFix missing geometry paths before importing. ', ...
                    'No files have been changed.\n']);
        return;
    end

    % Create a unique model name and import to a NEW model.
    [~, baseName] = fileparts(xmlName);
    safeName = matlab.lang.makeValidName(['RobotImported_' baseName]);
    modelName = safeName;
    suffix = 1;
    while bdIsLoaded(modelName) || isfile([modelName '.slx'])
        modelName = sprintf('%s_%d', safeName, suffix);
        suffix = suffix + 1;
    end

    if exist('smimport', 'file') ~= 2
        error(['smimport was not found. Install/enable Simscape Multibody ', ...
               'and confirm it is available in this MATLAB session.']);
    end

    fprintf('\nImporting XML into a NEW model: %s\n', modelName);
    fprintf('Original XML/STL files will not be modified.\n');

    try
        smimport(xmlPath, 'ModelName', modelName);
    catch ME
        fprintf(2, '\nsmimport failed:\n%s\n', ME.message);
        fprintf(2, ['Check that the XML was generated by a compatible ', ...
                    'Simscape Multibody Link exporter and that all STL ', ...
                    'files are accessible.\n']);
        rethrow(ME);
    end

    open_system(modelName);
    fprintf('\nImport completed.\n');
    fprintf(['\nNEXT: To align the whole robot without damaging assembly:\n', ...
        '1. In the imported model, identify the frame that represents Base.\n', ...
        '2. Inspect the Base frame relative to World Frame using Mechanics Explorer.\n', ...
        '3. Apply ONE rigid transform at the assembly root (World-to-Base/root),\n', ...
        '   not separate offsets to each STL or each joint transform.\n', ...
        '4. If Base is already the root frame connected to World at zero, no\n', ...
        '   global translation is needed; only local joint frames may need review.\n\n', ...
        'This script intentionally does not guess which body is Base: STL names\n', ...
        'and XML element order are not reliable indicators of the robot base.\n', ...
        'To automate the final transform, the XML structure or imported model\n', ...
        'must be inspected to identify the exact Base frame and root connection.\n']);
end
